BEGIN;
CREATE TABLE IF NOT EXISTS zones (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, tagline TEXT NOT NULL, description TEXT NOT NULL,
  price_per_hour INTEGER NOT NULL CHECK (price_per_hour >= 0), capacity INTEGER NOT NULL CHECK (capacity > 0), image TEXT, accent_hex TEXT
);
CREATE TABLE IF NOT EXISTS slots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id TEXT NOT NULL REFERENCES zones(id), date TEXT NOT NULL, time TEXT NOT NULL,
  booked INTEGER NOT NULL DEFAULT 0 CHECK (booked IN (0, 1)), UNIQUE(zone_id, date, time)
);
CREATE TABLE IF NOT EXISTS bookings (
  id TEXT PRIMARY KEY, zone_id TEXT NOT NULL REFERENCES zones(id), slot_id INTEGER NOT NULL REFERENCES slots(id),
  name TEXT NOT NULL, phone TEXT NOT NULL, email TEXT, party_size INTEGER NOT NULL DEFAULT 1 CHECK (party_size > 0),
  status TEXT NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'cancelled')),
  created_at TEXT NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text)
);
CREATE TABLE IF NOT EXISTS members (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, phone TEXT NOT NULL UNIQUE,
  tier TEXT NOT NULL CHECK (tier IN ('bronze', 'silver', 'gold')),
  joined_at TEXT NOT NULL DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text)
);
CREATE TABLE IF NOT EXISTS events (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, game TEXT NOT NULL, date TEXT NOT NULL,
  prize_pool INTEGER NOT NULL, slots INTEGER NOT NULL, registered INTEGER NOT NULL DEFAULT 0,
  category TEXT NOT NULL, CHECK (registered >= 0 AND registered <= slots)
);
CREATE INDEX IF NOT EXISTS idx_slots_lookup ON slots(zone_id, date);
CREATE INDEX IF NOT EXISTS idx_bookings_slot ON bookings(slot_id);
CREATE INDEX IF NOT EXISTS idx_bookings_made ON bookings(created_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_bookings_active_slot ON bookings(slot_id) WHERE status = 'confirmed';
-- The Next.js server connects with a database-owner credential. No browser
-- access is granted to bookings or members through Supabase's public Data API.
ALTER TABLE zones ENABLE ROW LEVEL SECURITY;
ALTER TABLE slots ENABLE ROW LEVEL SECURITY;
ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
COMMIT;
